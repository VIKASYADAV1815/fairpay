import * as Print from 'expo-print';
import * as Sharing from 'expo-sharing';
import type { Trip } from '@/store/trips';
import { computeBalances, minimizeTransfers } from '@/lib/settle';
import { formatMoney } from '@/lib/currency';

export async function shareTripPdf(trip: Trip) {
  const currency = trip.currency ?? 'INR';
  const total = trip.expenses.reduce((a, e) => a + e.amount, 0);
  const balances = computeBalances(trip.members, trip.expenses);
  const transfers = minimizeTransfers(balances);

  const expenseRows = trip.expenses
    .map(
      (e) =>
        `<tr><td>${escapeHtml(e.title)}${e.recurring ? ' 🔁' : ''}</td><td>${escapeHtml(formatMoney(e.amount, currency))}</td></tr>`,
    )
    .join('');

  const transferRows = transfers
    .map(
      (t) =>
        `<tr><td>${escapeHtml(t.fromName)} → ${escapeHtml(t.toName)}</td><td>${escapeHtml(formatMoney(t.amount, currency))}</td></tr>`,
    )
    .join('');

  const html = `
  <html>
    <head>
      <meta charset="utf-8" />
      <style>
        body { font-family: -apple-system, Helvetica, Arial, sans-serif; padding: 32px; color: #111; }
        h1 { font-size: 28px; margin: 0 0 4px; }
        .sub { color: #666; margin-bottom: 24px; }
        .lime { background: #B2FF24; display: inline-block; padding: 4px 10px; border-radius: 999px; font-size: 12px; font-weight: 700; color: #0A0A0A; }
        .hero { font-size: 40px; font-weight: 800; letter-spacing: -1px; margin: 16px 0 28px; }
        table { width: 100%; border-collapse: collapse; margin-bottom: 24px; }
        td { padding: 10px 0; border-bottom: 1px solid #eee; font-size: 14px; }
        td:last-child { text-align: right; font-weight: 700; }
        h2 { font-size: 14px; text-transform: uppercase; letter-spacing: 0.06em; color: #888; }
        .footer { margin-top: 40px; font-size: 12px; color: #999; }
      </style>
    </head>
    <body>
      <div class="lime">Fairpay · ${trip.purpose ? escapeHtml(trip.purpose) : 'Group'} report · ${currency}</div>
      <h1>${escapeHtml(trip.name)}</h1>
      <div class="sub">${trip.members.length} people · ${trip.expenses.length} expenses${trip.potCashback ? ` · ${escapeHtml(formatMoney(trip.potCashback, currency))} pot` : ''}</div>
      <div class="hero">${escapeHtml(formatMoney(total, currency))}</div>
      <h2>Expenses</h2>
      <table>${expenseRows || '<tr><td>No expenses</td><td></td></tr>'}</table>
      <h2>Settlements</h2>
      <table>${transferRows || `<tr><td>All clear</td><td>${escapeHtml(formatMoney(0, currency))}</td></tr>`}</table>
      <div class="footer">Generated by Fairpay · Zero-friction settlements</div>
    </body>
  </html>`;

  const { uri } = await Print.printToFileAsync({ html });
  if (await Sharing.isAvailableAsync()) {
    await Sharing.shareAsync(uri, {
      mimeType: 'application/pdf',
      dialogTitle: `${trip.name} — Fairpay report`,
      UTI: 'com.adobe.pdf',
    });
  }
  return uri;
}

function escapeHtml(s: string) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}
